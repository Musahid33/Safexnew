/**
 * Turn the uploaded SafetyOS design file into modules the app can mount.
 *
 * `SafetyOS — Employee Profile Preview (2).html` is a self-contained page: ~615 lines of
 * CSS, ~600 of markup and ~1260 of vanilla JS driving 18 screens (Case Management,
 * Training Management, Employee Profile, Communications, Document Vault, Audit &
 * Inspection, Form Builder, DM, User & Access, Dashboard, Analytics, Certificates, Export
 * Reports, Direct Data Entry, Daily Management, System Settings), SVG charts, a form
 * builder and CSV / report export.
 *
 * Rewriting that by hand into React would take weeks and would drift from the design the
 * moment either side changed. So the design runs as the design: this script splits it into
 * three generated files and the app mounts them.
 *
 * The only edits made to the author's code are seams, all documented below:
 *   1. every CSS selector is scoped under `.sos` so the design cannot collide with the
 *      worker app's globals.css (both define .app, .page, .sidebar, .modal, --line, --green),
 *   2. the demo employee array becomes `window.__SAFEX_EMPLOYEES__ || []` so the
 *      verified operator session can hand the console the real employee master,
 *   3. the demo case-report array becomes `window.__SAFEX_CASE_REPORTS__ || []` so the
 *      console lists the reports workers actually submitted, and a status change calls
 *      `window.__SAFEX_CASE_CHANGED__(record, previousStatus)` so the host can persist it,
 *   4. employee profile save/delete call `window.__SAFEX_EMPLOYEE_CHANGED__` with the
 *      record and its previous value, so the host can write the change and put the record
 *      back if the server refuses it.
 *
 * Run it after editing the design; never hand-edit the generated files.
 *
 *   npm run design:extract                      # uses the design file in the repo root
 *   node scripts/extract-design.mjs other.html   # explicit input
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_INPUT = resolve(ROOT, 'SafetyOS — Employee Profile Preview (2).html');
const input = process.argv[2] ? resolve(process.argv[2]) : DEFAULT_INPUT;

const src = readFileSync(input, 'utf8');
const OUT_DIR = resolve(ROOT, 'app/components/safetyos/generated');
mkdirSync(OUT_DIR, { recursive: true });

const BANNER =
  '/* GENERATED by scripts/extract-design.mjs from the uploaded SafetyOS design — do not edit by hand. */\n';

/* ------------------------------------------------------------------ 1. CSS */

const styleMatch = /<style>([\s\S]*?)<\/style>/.exec(src);
if (!styleMatch) throw new Error('no <style> block found in the design file');
const css = styleMatch[1];

/**
 * Scope one selector group under `.sos`.
 *
 * `:root`, `html` and `body` collapse onto `.sos` itself so the design's custom properties
 * and base typography stay inside its own subtree instead of leaking into the worker app.
 */
function prefixSelector(selector) {
  return selector
    .split(',')
    .map((raw) => {
      const part = raw.trim().replace(/\s+/g, ' ');
      if (!part) return null;
      if (part === ':root' || part === 'html' || part === 'body') return '.sos';
      if (part === '*') return '.sos *';
      if (/^:root\b/.test(part)) return `.sos${part.slice(5)}`;
      // html.auth-required ... — the host replaces the design's Supabase gate with its own
      // server-verified one, so those states are never applied. Scoping them keeps the rule
      // inert without changing the rest of the sheet.
      if (/^(html|body)\b/.test(part)) return `.sos${part.replace(/^(html|body)/, '')}`;
      return `.sos ${part}`;
    })
    .filter(Boolean)
    .join(',');
}

/** Walk the sheet, recursing into at-rules so nested @media blocks are scoped too. */
function scopeCss(text) {
  let out = '';
  let i = 0;
  while (i < text.length) {
    const brace = text.indexOf('{', i);
    if (brace === -1) {
      out += text.slice(i);
      break;
    }
    const selector = text.slice(i, brace);
    let depth = 1;
    let j = brace + 1;
    while (j < text.length && depth > 0) {
      if (text[j] === '{') depth += 1;
      else if (text[j] === '}') depth -= 1;
      j += 1;
    }
    const body = text.slice(brace + 1, j - 1);
    const head = selector.trim();
    if (head.startsWith('@media') || head.startsWith('@supports') || head.startsWith('@layer') || head.startsWith('@container')) {
      out += `${selector}{${scopeCss(body)}}`;
    } else if (head.startsWith('@')) {
      out += `${selector}{${body}}`; // @keyframes, @font-face, @page
    } else {
      out += `${prefixSelector(selector)}{${body}}`;
    }
    i = j;
  }
  return out;
}

const scopedCss = scopeCss(css);
writeFileSync(
  resolve(ROOT, 'app/safetyos.css'),
  `/* GENERATED by scripts/extract-design.mjs — do not edit by hand.\n`
  + ` * Source: ${input.slice(ROOT.length + 1)}\n`
  + ` * Every selector is scoped under .sos so the design cannot collide with globals.css.\n`
  + ` * Regenerate with \`npm run design:extract\` after editing the design.\n`
  + ` */\n${scopedCss}\n`
);

/* --------------------------------------------------------------- 2. markup */

/**
 * Markup is everything between <body> and the page's own <script>.
 *
 * Not a <body>…</body> regex: the report-export function builds a whole HTML document
 * inside a template literal, so the first </body> in the file belongs to that string and a
 * lazy match would swallow the entire script.
 */
const bodyStart = src.indexOf('<body>') + '<body>'.length;
const scriptStart = src.indexOf('<script>', bodyStart);
if (bodyStart < 6 || scriptStart === -1) throw new Error('could not locate the body/script boundary');
const markup = src.slice(bodyStart, scriptStart).trim();

writeFileSync(
  resolve(OUT_DIR, 'markup.ts'),
  `${BANNER}export const DESIGN_MARKUP = ${JSON.stringify(markup)};\n`
);

/* --------------------------------------------------------------- 3. script */

const scriptEnd = src.indexOf('</script>', scriptStart);
if (scriptEnd === -1) throw new Error('unterminated <script>');
let script = src.slice(scriptStart + '<script>'.length, scriptEnd);

/**
 * EMPLOYEE SEAM — the one deliberate change to the design's own code.
 *
 * Only the authenticated host may supply employees. The standalone design stays empty.
 */
const anchor = 'const employeeDirectory=';
const seamStart = script.indexOf(anchor);
if (seamStart === -1) throw new Error('EMPLOYEE SEAM: could not find `const employeeDirectory=`');
const arrayEnd = script.indexOf('];', seamStart);
if (arrayEnd === -1) throw new Error('EMPLOYEE SEAM: could not find the end of the demo employee array');

script =
  script.slice(0, seamStart)
  + `      const employeeDirectory=(typeof window!=='undefined'&&Array.isArray(window.__SAFEX_EMPLOYEES__))?window.__SAFEX_EMPLOYEES__:[];`
  + script.slice(arrayEnd + 1); // drop the `;` that closed the original declaration

/**
 * EMPLOYEE PROFILE SEAM — profile edits are written by the host, not just remembered.
 *
 * The design only ever edited its own array: the form showed "Employee profile updated."
 * and the change was gone on reload. These seams hand the saved / deleted record to the
 * host, which writes it through the admin session and hands back a promise; the console
 * re-renders when that promise settles, so a rejected write visibly returns to the stored
 * value instead of leaving a row that claims to be saved.
 */
const defaultsAnchor = "employeeDirectory.forEach(emp=>Object.assign(emp,{mobile:'',email:'',gender:'',dob:'',bloodGroup:'',emergencyName:'',emergencyMobile:'',location:'',address:'',notes:'',photo:'',previousNames:[]}));";
if (!script.includes(defaultsAnchor)) throw new Error('EMPLOYEE SEAM: could not find the profile defaults');

script = script.replace(
  defaultsAnchor,
  // Fill only what is missing. The old code overwrote every field, which blanked the mobile
  // number and blood group the roster had just supplied.
  `employeeDirectory.forEach(emp=>{const __employeeDefaults={mobile:'',email:'',gender:'',dob:'',bloodGroup:'',emergencyName:'',emergencyMobile:'',location:'',address:'',notes:'',photo:'',previousNames:[]};Object.keys(__employeeDefaults).forEach(key=>{if(emp[key]===undefined||emp[key]===null)emp[key]=__employeeDefaults[key]})});
      function notifyEmployeeChange(action,record,previous){try{if(typeof window!=='undefined'&&window.__SAFEX_EMPLOYEE_CHANGED__)return window.__SAFEX_EMPLOYEE_CHANGED__({action,record,previous:previous||null})}catch(error){console.error('Safex employee sync failed',error);return null}return null}`
);

const saveAnchor = "if(existing){if(existing.name&&existing.name.toLowerCase()!==name.toLowerCase()&&!previousNames.some(value=>value.toLowerCase()===existing.name.toLowerCase()))previousNames.push(existing.name);if(oldId!==employeeNo)rekeyEmployeeLogIds(oldId,employeeNo);Object.assign(existing,profile,{previousNames})}else{employeeDirectory.push({...profile,previousNames:[]})}";
if (!script.includes(saveAnchor)) throw new Error('EMPLOYEE SEAM: could not find the profile save');
script = script.replace(
  saveAnchor,
  `const __employeePrevious=existing?{...existing}:null;${saveAnchor}const __employeeRecord=existing||employeeDirectory[employeeDirectory.length-1];const __employeeSync=notifyEmployeeChange(existing?'update':'create',__employeeRecord,__employeePrevious);if(__employeeSync&&typeof __employeeSync.then===\"function\"){__employeeSync.then(()=>renderEmployeeProfilePage(),()=>renderEmployeeProfilePage())}`
);

const deleteAnchor = "const index=employeeDirectory.findIndex(item=>String(item.id)===String(id));if(index>=0)employeeDirectory.splice(index,1);";
if (!script.includes(deleteAnchor)) throw new Error('EMPLOYEE SEAM: could not find the profile delete');
script = script.replace(
  deleteAnchor,
  "const index=employeeDirectory.findIndex(item=>String(item.id)===String(id));const __employeeRemoved=index>=0?employeeDirectory.splice(index,1)[0]:null;const __employeeDelete=notifyEmployeeChange('delete',__employeeRemoved,null);if(__employeeDelete&&typeof __employeeDelete.then===\"function\"){__employeeDelete.then(()=>renderEmployeeProfilePage(),()=>renderEmployeeProfilePage())}"
);

// The mobile number is personal data and is withheld when PII release is off, so the form
// arrives empty. Requiring it would make every profile edit fail for a reason that has
// nothing to do with the field the operator changed.
const mobileAnchor = "const mobilePattern=/^\\+?[\\d\\s().-]{7,20}$/;if(!mobilePattern.test(mobile)){toast('Enter a valid mobile number.');$('#epMobile').focus();return}";
if (!script.includes(mobileAnchor)) throw new Error('EMPLOYEE SEAM: could not find the mobile validation');
script = script.replace(
  mobileAnchor,
  "const mobilePattern=/^\\+?[\\d\\s().-]{7,20}$/;if(mobile&&!mobilePattern.test(mobile)){toast('Enter a valid mobile number.');$('#epMobile').focus();return}"
);

// The design said "updated" before the server had a say. The host reports the real result,
// so the design's own toast only says that a save is under way.
const saveToastAnchor = "toast(existing?'Employee profile updated.':'Employee profile added to the master directory.');";
if (!script.includes(saveToastAnchor)) throw new Error('EMPLOYEE SEAM: could not find the profile save toast');
script = script.replace(saveToastAnchor, "toast('Saving employee profile…');");

/**
 * CASE-REPORT SEAM — the console's case list is fed by the host.
 *
 * `caseReports` is the array every screen reads (Case Management, Dashboard, Analytics,
 * Export). The design seeds it empty; the host fills it from /api/admin/reports. Direct
 * entry and delete still mutate it locally, which is why the host blocks those two actions
 * for server-backed records instead of letting the console show unsaved changes.
 */
const reportsAnchor = 'const caseReports=[];';
if (!script.includes(reportsAnchor)) throw new Error('REPORT SEAM: could not find `const caseReports=[];`');
script = script.replace(
  reportsAnchor,
  `const caseReports=(typeof window!=='undefined'&&Array.isArray(window.__SAFEX_CASE_REPORTS__))?window.__SAFEX_CASE_REPORTS__:[];
      function notifyCaseChange(record,previousStatus){try{if(typeof window!=='undefined'&&window.__SAFEX_CASE_CHANGED__)return window.__SAFEX_CASE_CHANGED__(record,previousStatus)}catch(error){console.error('Safex case sync failed',error);return null}return null}`
);

// The inline status dropdown is the one edit the console can persist, so it reports the
// old value too: the host needs it to put the row back if the server refuses.
const statusAnchor = 'record.status=select.value;renderCaseManagement();';
if (!script.includes(statusAnchor)) throw new Error('REPORT SEAM: could not find the status-change handler');
script = script.replace(
  statusAnchor,
  'const __previousStatus=record.status;record.status=select.value;const __caseSync=notifyCaseChange(record,__previousStatus);renderCaseManagement();if(__caseSync&&typeof __caseSync.then==="function"){__caseSync.then(()=>renderCaseManagement(),()=>renderCaseManagement())}'
);


writeFileSync(
  resolve(OUT_DIR, 'script.ts'),
  `${BANNER}export const DESIGN_SCRIPT = ${JSON.stringify(script)};\n`
);

console.log('design :', input.slice(ROOT.length + 1));
console.log('css    :', scopedCss.length, 'bytes -> app/safetyos.css');
console.log('markup :', markup.length, 'bytes -> app/components/safetyos/generated/markup.ts');
console.log('script :', script.length, 'bytes -> app/components/safetyos/generated/script.ts');
